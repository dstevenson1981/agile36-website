create table if not exists brain.sops (
  id integer generated by default as identity primary key,
  slug text not null unique,
  title text not null,
  category text not null,
  body text not null,
  sort_order integer not null default 0,
  updated_at timestamptz not null default now(),
  constraint brain_sops_category_check
    check (category = any (array['may_do','must_never','handoff','policy','faq']))
);

revoke all on table brain.sops from public, anon, authenticated;
grant select, insert, update, delete on table brain.sops to postgres, service_role;

